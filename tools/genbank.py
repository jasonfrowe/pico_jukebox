# Simple "Filler" Logic to ensure the array has 128 entries
# (The list above is truncated for the chat, but the code below handles safe filling)
full_bank = melodic_data + [0] * (11 * (128 - (len(melodic_data)//11)))

# Generate instruments.c
with open("instruments.c", "w") as f:
    f.write('#include "instruments.h"\n\n')
    f.write('// Auto-generated Standard Bank (AdLib Compatible)\n')
    f.write('OPL_Patch gm_bank[128] = {\n')

    ATTENUATION = 0 
    
    for i in range(128):
        base = i * 11
        if base + 10 < len(full_bank):
            d = list(full_bank[base:base+11]) # Make a mutable copy
            
            # --- APPLY HEADROOM AUTOMATICALLY ---
            # Index 6 is C_KSL_TL (Carrier Level). Format: [KSL:2][TL:6]
            # We want to increase the TL part (making it quieter) without touching KSL.
            
            original_ksl = d[6] & 0xC0 # Keep the top 2 bits (Key Scale)
            original_tl  = d[6] & 0x3F # Get the bottom 6 bits (Volume)
            
            new_tl = original_tl + ATTENUATION
            if new_tl > 63: new_tl = 63 # Clamp to silence
            
            d[6] = original_ksl | new_tl # Pack it back
            
            # Write the data
            f.write(f'    [{i}] = {{ .m_ave=0x{d[0]:02X}, .m_ksl=0x{d[1]:02X}, .m_atdec=0x{d[2]:02X}, .m_susrel=0x{d[3]:02X}, .m_wave=0x{d[4]:02X}, ')
            f.write(f'.c_ave=0x{d[5]:02X}, .c_ksl=0x{d[6]:02X}, .c_atdec=0x{d[7]:02X}, .c_susrel=0x{d[8]:02X}, .c_wave=0x{d[9]:02X}, .feedback=0x{d[10]:02X} }},\n')
        else:
            # Fallback (Also attenuated)
            f.write(f'    [{i}] = {{ .m_ave=0x01, .m_ksl=0x10, .m_atdec=0xF0, .m_susrel=0xF3, .m_wave=0x00, .c_ave=0x01, .c_ksl=0x{0x00+ATTENUATION:02X}, .c_atdec=0xF0, .c_susrel=0xF3, .c_wave=0x00, .feedback=0x04 }}, // Default\n')
            
    f.write('};\n\n')
    
    # f.write('const OPL_Patch drum_bd    = { .m_ave=0x00, .m_ksl=0x00, .m_atdec=0xF1, .m_susrel=0xCF, .m_wave=0x00, .c_ave=0x00, .c_ksl=0x00, .c_atdec=0xF1, .c_susrel=0xCF, .c_wave=0x00, .feedback=0x00 };\n')
    # f.write('const OPL_Patch drum_bd    = { .m_ave=0x00, .m_ksl=0x00, .m_atdec=0xF1, .m_susrel=0x5F, .m_wave=0x00, .c_ave=0x00, .c_ksl=0x00, .c_atdec=0xF2, .c_susrel=0x08, .c_wave=0x00, .feedback=0x00 };\n')
    f.write('const OPL_Patch drum_bd    = { .m_ave=0x00, .m_ksl=0x0D, .m_atdec=0xE8, .m_susrel=0xEF, .m_wave=0x00, .c_ave=0x00, .c_ksl=0x00, .c_atdec=0xA5, .c_susrel=0xFF, .c_wave=0x00, .feedback=0x06 };\n')
    f.write('const OPL_Patch drum_snare = { .m_ave=0x06, .m_ksl=0x00, .m_atdec=0xF0, .m_susrel=0xF0, .m_wave=0x00, .c_ave=0x00, .c_ksl=0x00, .c_atdec=0xF7, .c_susrel=0xF7, .c_wave=0x00, .feedback=0x0E };\n')
    f.write('const OPL_Patch drum_hihat = { .m_ave=0x05, .m_ksl=0x00, .m_atdec=0xF0, .m_susrel=0x77, .m_wave=0x00, .c_ave=0x00, .c_ksl=0x00, .c_atdec=0xFA, .c_susrel=0xEA, .c_wave=0x00, .feedback=0x0E };\n')
    
    # Add helper functions
    f.write('\n// --- INTERNAL HELPER ---\n')
    f.write('\n// Global Shadow for Volume Scaling\n')
    f.write('uint8_t shadow_carrier_ksl[9] = {0};\n\n') # Define the array
    f.write('void write_patch_to_channel(uint8_t ch, const OPL_Patch* p) {\n')
    f.write('    if (ch > 8) return;\n')
    f.write('    uint8_t offsets[9] = {0, 1, 2, 8, 9, 10, 16, 17, 18};\n')
    f.write('    uint8_t off = offsets[ch];\n\n')
    f.write('    opl_write(false, 0x20 + off); opl_write(true, p->m_ave);\n')
    f.write('    opl_write(false, 0x40 + off); opl_write(true, p->m_ksl);\n')
    f.write('    opl_write(false, 0x60 + off); opl_write(true, p->m_atdec);\n')
    f.write('    opl_write(false, 0x80 + off); opl_write(true, p->m_susrel);\n')
    f.write('    opl_write(false, 0xE0 + off); opl_write(true, p->m_wave);\n\n')
    f.write('    // Save Base KSL for Velocity Scaling\n')
    f.write('    shadow_carrier_ksl[ch] = p->c_ksl;\n\n')
    f.write('    opl_write(false, 0x23 + off); opl_write(true, p->c_ave);\n')
    f.write('    opl_write(false, 0x43 + off); opl_write(true, p->c_ksl);\n')
    f.write('    opl_write(false, 0x63 + off); opl_write(true, p->c_atdec);\n')
    f.write('    opl_write(false, 0x83 + off); opl_write(true, p->c_susrel);\n')
    f.write('    opl_write(false, 0xE3 + off); opl_write(true, p->c_wave);\n\n')
    f.write('    opl_write(false, 0xC0 + ch);  opl_write(true, p->feedback);\n')
    f.write('}\n\n')
    
    f.write('void load_gm_instrument(uint8_t channel, uint8_t program_number) {\n')
    f.write('    if (program_number > 127) program_number = 0;\n')
    f.write('    write_patch_to_channel(channel, &gm_bank[program_number]);\n')
    f.write('}\n\n')
    
    f.write('void load_drum_patch(uint8_t channel, uint8_t drum_note) {\n')
    f.write('    if (drum_note == 35 || drum_note == 36) write_patch_to_channel(channel, &drum_bd);\n')
    f.write('    else if (drum_note == 38 || drum_note == 40) write_patch_to_channel(channel, &drum_snare);\n')
    f.write('    else write_patch_to_channel(channel, &drum_hihat);\n')
    f.write('}\n')

    f.write('void update_gm_patch(uint8_t program_number, const OPL_Patch* new_patch) {\n')
    f.write('    if (program_number > 127) return;\n')
    f.write('    gm_bank[program_number] = *new_patch; // Struct copy\n')
    f.write('    \n')
    f.write('    // Also update the shadow volume used for velocity scaling\n')
    f.write('    shadow_carrier_ksl[program_number] = new_patch->c_ksl;\n')
    f.write('}\n\n')

print("instruments.c generated successfully.")

