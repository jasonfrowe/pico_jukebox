            f.write(f'    [{i}] = {{ .m_ave=0x{d[0]:02X}, .m_ksl=0x{d[1]:02X}, .m_atdec=0x{d[2]:02X}, .m_susrel=0x{d[3]:02X}, .m_wave=0x{d[4]:02X}, ')
